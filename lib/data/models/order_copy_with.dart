import 'order.dart';
import 'reward_breakdown.dart';

// Sentinel used to distinguish "not provided" from an explicit null in copyWith.
const _unset = Object();

/// Extension hosting the full-field `copyWith` for [Order].
///
/// Living as an extension keeps `order.dart` focused on the immutable data
/// schema while preserving the familiar `order.copyWith(...)` call site.
extension OrderCopyWith on Order {
  Order copyWith({
    String? id,
    OrderType? type,
    List<WasteType>? wasteTypes,
    String? pickupAddress,
    String? dropoffAddress,
    OrderStatus? status,
    String? driverName,
    String? driverPhone,
    double? driverRating,
    String? driverVehicle,
    String? driverVehicleModel,
    String? driverVehicleColor,
    String? driverLicensePlate,
    String? driverVehiclePhotoPath,
    String? supplierName,
    double? reward,
    double? weightKg,
    DateTime? createdAt,
    DateTime? acceptedAt,
    DateTime? inTransitAt,
    DateTime? completedAt,
    DateTime? scheduledAt,
    String? eta,
    double? distanceKm,
    String? proofImagePath,
    double? paidAmount,
    String? supplierNotes,
    List<String>? images,
    double? estimatedWeightKg,
    WasteForm? wasteForm,
    WeightCategory? weightCategory,
    double? deliveryFee,
    PickupTarget? pickupTarget,
    double? itemPrice,
    String? jobDescription,
    double? pricePerKg,
    PaymentModel? paymentModel,
    double? minQuantityKg,
    bool? isEdited,
    DateTime? editedAt,
    String? editNote,
    String? linkedJobId,
    CollectionDeliveryMethod? collectionDeliveryMethod,
    CollectionTransactionType? collectionTransactionType,
    double? pickupLat,
    double? pickupLng,
    double? dropoffLat,
    double? dropoffLng,
    Object? etaMinutes = _unset,
    bool? isMarketplaceShared,
    bool? requiresRider,
    RewardBreakdown? rewardBreakdown,
    List<InvoiceItem>? invoices,
  }) {
    return Order(
      id: id ?? this.id,
      type: type ?? this.type,
      wasteTypes: wasteTypes ?? this.wasteTypes,
      pickupAddress: pickupAddress ?? this.pickupAddress,
      dropoffAddress: dropoffAddress ?? this.dropoffAddress,
      status: status ?? this.status,
      driverName: driverName ?? this.driverName,
      driverPhone: driverPhone ?? this.driverPhone,
      driverRating: driverRating ?? this.driverRating,
      driverVehicle: driverVehicle ?? this.driverVehicle,
      driverVehicleModel: driverVehicleModel ?? this.driverVehicleModel,
      driverVehicleColor: driverVehicleColor ?? this.driverVehicleColor,
      driverLicensePlate: driverLicensePlate ?? this.driverLicensePlate,
      driverVehiclePhotoPath:
          driverVehiclePhotoPath ?? this.driverVehiclePhotoPath,
      supplierName: supplierName ?? this.supplierName,
      reward: reward ?? this.reward,
      weightKg: weightKg ?? this.weightKg,
      createdAt: createdAt ?? this.createdAt,
      acceptedAt: acceptedAt ?? this.acceptedAt,
      inTransitAt: inTransitAt ?? this.inTransitAt,
      completedAt: completedAt ?? this.completedAt,
      scheduledAt: scheduledAt ?? this.scheduledAt,
      eta: eta ?? this.eta,
      distanceKm: distanceKm ?? this.distanceKm,
      proofImagePath: proofImagePath ?? this.proofImagePath,
      paidAmount: paidAmount ?? this.paidAmount,
      supplierNotes: supplierNotes ?? this.supplierNotes,
      images: images ?? this.images,
      estimatedWeightKg: estimatedWeightKg ?? this.estimatedWeightKg,
      wasteForm: wasteForm ?? this.wasteForm,
      weightCategory: weightCategory ?? this.weightCategory,
      deliveryFee: deliveryFee ?? this.deliveryFee,
      pickupTarget: pickupTarget ?? this.pickupTarget,
      itemPrice: itemPrice ?? this.itemPrice,
      jobDescription: jobDescription ?? this.jobDescription,
      pricePerKg: pricePerKg ?? this.pricePerKg,
      paymentModel: paymentModel ?? this.paymentModel,
      minQuantityKg: minQuantityKg ?? this.minQuantityKg,
      isEdited: isEdited ?? this.isEdited,
      editedAt: editedAt ?? this.editedAt,
      editNote: editNote ?? this.editNote,
      linkedJobId: linkedJobId ?? this.linkedJobId,
      collectionDeliveryMethod:
          collectionDeliveryMethod ?? this.collectionDeliveryMethod,
      collectionTransactionType:
          collectionTransactionType ?? this.collectionTransactionType,
      pickupLat: pickupLat ?? this.pickupLat,
      pickupLng: pickupLng ?? this.pickupLng,
      dropoffLat: dropoffLat ?? this.dropoffLat,
      dropoffLng: dropoffLng ?? this.dropoffLng,
      etaMinutes: etaMinutes == _unset ? this.etaMinutes : etaMinutes as int?,
      isMarketplaceShared: isMarketplaceShared ?? this.isMarketplaceShared,
      requiresRider: requiresRider ?? this.requiresRider,
      rewardBreakdown: rewardBreakdown ?? this.rewardBreakdown,
      invoices: invoices ?? this.invoices,
    );
  }
}
